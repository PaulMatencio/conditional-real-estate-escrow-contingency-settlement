#!/usr/bin/env node
/**
 * Generates the typed SDK (sdk/escrow) from the compiler's contract-info.json: one method per exported
 * impure circuit, wrapping midnight-js `callTx`. Re-run after every recompile.
 *
 *   node scripts/generate-sdk.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const cfg = JSON.parse(readFileSync(path.join(root, 'midnight.config.json'), 'utf8'));
const c = cfg.contract;
const info = JSON.parse(readFileSync(path.join(root, c.managedDir, 'compiler/contract-info.json'), 'utf8'));

const NAMED = new Set(['KycAttestation', 'KycPolicy', 'SchnorrSignature']);
function tsType(t) {
  switch (t['type-name']) {
    case 'Boolean': return 'boolean';
    case 'Field': case 'Uint': return 'bigint';
    case 'Bytes': return 'Uint8Array';
    case 'Opaque': return t.tsType === 'JubjubPoint' ? 'JubjubPoint' : t.tsType === 'string' ? 'string' : 'unknown';
    case 'Alias': return tsType(t.type);
    case 'Enum': return t.name;
    // Maybe<T>, ZswapCoinPublicKey, ShieldedCoinInfo, … are plain objects in the compiled module.
    case 'Struct': return NAMED.has(t.name) ? t.name : `{ ${t.elements.map((e) => `${e.name}: ${tsType(e.type)}`).join('; ')} }`;
    case 'Vector': return `${tsType(t.type)}[]`;
    case 'Tuple': return `[${t.types.map(tsType).join(', ')}]`;
    default: return 'unknown';
  }
}
// Maybe<T> is a Struct { is_some, value } in contract-info; expose it as the compiled shape.
const circuits = info.circuits.filter((x) => !x.pure && x.proof !== false);
const names = circuits.map((x) => x.name);

const methods = circuits.map((x) => {
  const params = x.arguments.map((a) => `${a.name}: ${tsType(a.type)}`).join(', ');
  const call = x.arguments.map((a) => a.name).join(', ');
  return `  /** Calls circuit \`${x.name}\`. */\n  async ${x.name}(${params}): Promise<TxData> {\n    return toTxData(await this.found.callTx.${x.name}(${call}));\n  }`;
});

const header = `// GENERATED by scripts/generate-sdk.mjs from ${c.name} (compiler ${info['compiler-version']}, language ${info['language-version']}). Do not edit.\n`;
mkdirSync(path.join(root, c.sdkDir), { recursive: true });
writeFileSync(path.join(root, c.sdkDir, 'types.ts'), `${header}import type { JubjubPoint } from '@midnight-ntwrk/compact-runtime';
export type { JubjubPoint };
export type { KycAttestation, KycPolicy, SchnorrSignature } from '../../${c.managedDir}/contract/index.js';
export { EscrowStatus, InitAttribute, Contingency, FinancingMode } from '../../${c.managedDir}/contract/index.js';

export interface TxData {
  txId: string;
  txHash: string;
  blockHeight: number;
}

/** Every circuit of the contract, in source order. */
export const CIRCUITS = ${JSON.stringify(names)} as const;
export type CircuitName = (typeof CIRCUITS)[number];
`);
writeFileSync(path.join(root, c.sdkDir, 'client.ts'), `${header}import { deployContract, findDeployedContract } from '@midnight-ntwrk/midnight-js-contracts';
import type { Contingency, FinancingMode, JubjubPoint, KycAttestation, KycPolicy, SchnorrSignature, TxData } from './types.js';

type CallResult = { public: { txId: string; txHash: string; blockHeight: number } };
type Found = { callTx: Record<string, (...a: any[]) => Promise<CallResult>>; deployTxData: { public: { contractAddress: string } } };

const toTxData = (r: CallResult): TxData => ({ txId: String(r.public.txId), txHash: r.public.txHash, blockHeight: r.public.blockHeight });

/** Typed wrapper over midnight-js callTx for the escrow contract. */
export class EscrowClient {
  private constructor(private readonly found: Found) {}

  /** Constructor args: admin, buyer, seller, color, ticker, then ten Maybe<…> terms (see the contract). */
  static async deploy(providers: unknown, compiledContract: unknown, args: unknown[]): Promise<EscrowClient> {
    const found = await (deployContract as any)(providers, { compiledContract, args });
    return new EscrowClient(found as Found);
  }

  static async connect(providers: unknown, compiledContract: unknown, contractAddress: string): Promise<EscrowClient> {
    const found = await (findDeployedContract as any)(providers, { compiledContract, contractAddress });
    return new EscrowClient(found as Found);
  }

  get contractAddress(): string {
    return this.found.deployTxData.public.contractAddress;
  }

${methods.join('\n\n')}
}
`);
writeFileSync(path.join(root, c.sdkDir, 'index.ts'), `${header}export * from './client.js';
export * from './types.js';
export { Contract, ledger, pureCircuits } from '../../${c.managedDir}/contract/index.js';
export type { Ledger, Witnesses, ImpureCircuits, PureCircuits, Circuits } from '../../${c.managedDir}/contract/index.js';
`);
console.log(`[sdk] ${names.length} circuits -> ${c.sdkDir}`);
